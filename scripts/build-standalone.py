#!/usr/bin/env python3
"""Generate the traceable single-file DX standalone release artifact."""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import sys
import zipfile
from io import BytesIO
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
PACKAGE = SRC / "dx_artifacts"
RUNTIME = ROOT / "dx.py"


def canonical_bundle() -> bytes:
    output = BytesIO()
    with zipfile.ZipFile(
        output,
        "w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=9,
        strict_timestamps=True,
    ) as archive:
        for path in sorted(PACKAGE.glob("*.py")):
            if path.name == "_runtime.py":
                continue
            info = zipfile.ZipInfo(
                f"dx_artifacts/{path.name}",
                date_time=(1980, 1, 1, 0, 0, 0),
            )
            info.create_system = 3
            info.external_attr = (0o100644 << 16)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.extra = b""
            info.comment = b""
            archive.writestr(info, path.read_bytes(), compresslevel=9)

        info = zipfile.ZipInfo(
            "dx_artifacts/_runtime.py",
            date_time=(1980, 1, 1, 0, 0, 0),
        )
        info.create_system = 3
        info.external_attr = (0o100644 << 16)
        info.compress_type = zipfile.ZIP_DEFLATED
        info.extra = b""
        info.comment = b""
        archive.writestr(info, RUNTIME.read_bytes(), compresslevel=9)
    return output.getvalue()


def generate(version: str) -> bytes:
    bundle = canonical_bundle()
    encoded = base64.b64encode(bundle).decode("ascii")
    source_sha256 = hashlib.sha256(RUNTIME.read_bytes()).hexdigest()
    return f"""#!/usr/bin/env python3
# Generated by scripts/build-standalone.py. Do not edit.
# software-version: {version}
# source-runtime-sha256: {source_sha256}
from __future__ import annotations
import atexit
import base64
import sys
import tempfile
import zipfile
from io import BytesIO
from pathlib import Path

_BUNDLE = {encoded!r}
_TEMP = Path(tempfile.mkdtemp(prefix="dx-artifacts-"))
atexit.register(lambda: __import__("shutil").rmtree(_TEMP, ignore_errors=True))
with zipfile.ZipFile(BytesIO(base64.b64decode(_BUNDLE)), "r") as archive:
    archive.extractall(_TEMP)
sys.path.insert(0, str(_TEMP))
from dx_artifacts._standalone_runtime import load_main
raise SystemExit(load_main()())
""".encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--manifest", required=True)
    args = parser.parse_args()

    output = Path(args.output)
    manifest = Path(args.manifest)
    output.parent.mkdir(parents=True, exist_ok=True)
    manifest.parent.mkdir(parents=True, exist_ok=True)

    data = generate(args.version)
    temporary = output.with_name(output.name + ".tmp")
    temporary.write_bytes(data)
    os.chmod(temporary, 0o755)
    temporary.replace(output)

    evidence = {
        "schema_version": 1,
        "software_version": args.version,
        "source_release": f"dx-artifacts-{args.version}",
        "source_runtime": {
            "path": "dx.py",
            "bytes": RUNTIME.stat().st_size,
            "sha256": hashlib.sha256(RUNTIME.read_bytes()).hexdigest(),
        },
        "standalone": {
            "path": output.name,
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "generation_command": (
                "python3 scripts/build-standalone.py "
                f"--version {args.version} "
                f"--output {output.name} "
                f"--manifest {manifest.name}"
            ),
        },
    }
    manifest.write_text(
        json.dumps(evidence, sort_keys=True, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
